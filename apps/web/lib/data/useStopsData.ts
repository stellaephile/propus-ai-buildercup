/** DataMeet/OpenCity shapefiles disagree on the name key — try the usual suspects. */
export function wardNameOf(props: Record<string, unknown> | null | undefined): string {
  if (!props) return "";
  for (const k of ["Ward_Name", "WARD_NAME", "ward_name", "wardname", "Ward_No_Name", "name", "NAME"]) {
    const v = props[k];
    if (typeof v === "string" && v.trim()) return v.trim().toUpperCase();
  }
  return "";
}
