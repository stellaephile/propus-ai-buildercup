"use client";

import { useEffect, useState } from "react";
import { BUS_STOPS_SAMPLE } from "./busStopsSample";

/**
 * The clustered physical-stop tier (pipeline/cluster_stops.py, 40 m
 * complete-linkage in EPSG:32643). One entry per stop LOCATION — the two poles
 * either side of a road collapse to one. Evidence class Estimated, never
 * Observed: the merge is a spatial judgement, not a published fact.
 */
export interface PhysicalStopTier {
  /** cluster centroid [lon, lat], WGS84 (centroid computed in EPSG:32643) */
  points: [number, number][];
  /** distinct routes serving the cluster (union across its poles, not a sum) */
  w: number[];
  /** poles merged into this location — 1 = a lone stop, 2 = a to/from pair */
  m: number[];
  evidence: "Estimated";
}

export interface StopTiers {
  method: string;
  threshold_m: number;
  crs: string;
  /** cluster index per boarding point, parallel to StopsData.points */
  c: number[];
  boarding: { count: number; evidence: "Observed" };
  physical: PhysicalStopTier;
}

export interface StopsData {
  /** [lon, lat] pairs, WGS84 — always real coordinates. When `tiers` is
   *  present these are BOARDING POINTS (one per physical pole, Observed),
   *  not raw GTFS stop_id rows. */
  points: [number, number][];
  /** optional names parallel to points (full fixture only) */
  names?: string[];
  /** distinct routes serving each stop (Observed, from GTFS) — drives the
   *  zoom-out declutter; absent on the sample fixture */
  weights?: number[];
  /** Two-tier stop model driving the map's zoom-dependent expand: physical
   *  stop locations when zoomed out, individual boarding poles when zoomed in.
   *  Absent if the crosswalk has not been built — the map then shows the flat
   *  list at every zoom rather than inventing cluster membership. */
  tiers?: StopTiers;
  /** raw GTFS stop_id row count — kept for provenance. Larger than
   *  points.length whenever the tiers are present, because the feed lists the
   *  same pole once per serving route. */
  rawStopRows?: number;
  /** true when the FULL fixture is loaded; false = labelled sample */
  full: boolean;
}

/**
 * Loads the full stops fixture (public/fixtures/stops.json, generated by
 * scripts/build-fixtures.mjs from the raw GTFS) and falls back to the
 * committed real-data sample. The `full` flag drives honest labelling.
 */
export function useStopsData(): StopsData {
  const [data, setData] = useState<StopsData>({
    points: BUS_STOPS_SAMPLE,
    full: false,
  });

  useEffect(() => {
    let cancelled = false;
    fetch("/fixtures/stops.json")
      .then((r) => (r.ok ? r.json() : null))
      .then((j) => {
        if (cancelled || !j || !Array.isArray(j.points)) return;
        setData({
          points: j.points,
          names: j.names,
          weights: j.w,
          tiers: j.tiers,
          rawStopRows: j.raw_stop_rows,
          full: true,
        });
      })
      .catch(() => {});
    return () => {
      cancelled = true;
    };
  }, []);

  return data;
}

export function useWards(): GeoJSON.FeatureCollection | null {
  const [wards, setWards] = useState<GeoJSON.FeatureCollection | null>(null);
  useEffect(() => {
    let cancelled = false;
    fetch("/fixtures/wards.geojson")
      .then((r) => (r.ok ? r.json() : null))
      .then((j: GeoJSON.FeatureCollection | null) => {
        if (!cancelled && j && j.type === "FeatureCollection") {
          // enrich with a stable, uppercase __name so map filters can match
          // metric records without guessing the source's property key
          for (const f of j.features) {
            const p = (f.properties ?? {}) as Record<string, unknown>;
            p.__name = wardNameOf(p);
            f.properties = p;
          }
          setWards(j);
        }
      })
      .catch(() => {});
    return () => {
      cancelled = true;
    };
  }, []);
  return wards;
}

