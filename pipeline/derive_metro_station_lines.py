"""
pipeline/derive_metro_station_lines.py
---------------------------------------
Derive which metro line(s) serve each station from the raw DMRC GTFS
(data/raw/metro/) and generate apps/web/lib/data/metroStopLines.ts.

Line identity comes from the route_long_name prefix (RED_, PINK_, ...), the
same key metroLineTokens uses. A station served by 2+ distinct lines is an
interchange — the map renders those at every zoom ("key stations") with a
neutral ring; single-line stations get their line's identity ring and only
appear once zoomed in.

Usage: .venv/bin/python pipeline/derive_metro_station_lines.py
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw" / "metro"
OUT = ROOT / "apps" / "web" / "lib" / "data" / "metroStopLines.ts"


def main() -> int:
    with open(RAW / "routes.txt", newline="", encoding="utf-8-sig") as f:
        route_line = {
            r["route_id"]: (r["route_long_name"] or "").split("_", 1)[0]
            for r in csv.DictReader(f)
        }
    with open(RAW / "trips.txt", newline="", encoding="utf-8-sig") as f:
        trip_route = {r["trip_id"]: r["route_id"] for r in csv.DictReader(f)}
    with open(RAW / "stops.txt", newline="", encoding="utf-8-sig") as f:
        stop_name = {r["stop_id"]: r["stop_name"].strip() for r in csv.DictReader(f)}

    lines_by_station: dict[str, set[str]] = defaultdict(set)
    with open(RAW / "stop_times.txt", newline="", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            line = route_line.get(trip_route.get(r["trip_id"], ""), "")
            name = stop_name.get(r["stop_id"], "")
            if line and name:
                lines_by_station[name].add(line)

    stations = {name: sorted(lines) for name, lines in sorted(lines_by_station.items())}
    interchanges = sum(1 for v in stations.values() if len(v) > 1)

    body = json.dumps(stations, indent=2, ensure_ascii=False)
    OUT.write_text(
        "/**\n"
        " * GENERATED by pipeline/derive_metro_station_lines.py — do not edit.\n"
        " * Metro line(s) serving each station, derived from data/raw/metro GTFS\n"
        " * (© DMRC via OTD). Keys match METRO_STOPS names; values are\n"
        " * route_long_name prefixes, the same keys as metroLineTokens.\n"
        " * Evidence: Observed. 2+ lines = interchange.\n"
        " */\n"
        f"export const METRO_STOP_LINES: Record<string, string[]> = {body};\n"
    )
    print(f"{len(stations)} stations ({interchanges} interchanges) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
